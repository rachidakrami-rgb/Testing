# -*- coding: utf-8 -*-
"""time_speech — تحويل الوقت الرقمي (HH:MM) إلى نطق عربي طبيعي.

المشكلة: قراءة "08:53" رقماً برقم (صفر... ثمانية... خمسة... ثلاثة) تبدو آلية
وغير مفهومة في رسالة صوتية. هذه الوحدة توفّر منطقاً موحّداً (بدل تكراره في
كل من assistant.py و voice_bot.py) لتحويل الوقت إلى جملة طبيعية مثل:
"الساعة الثامنة وثلاث وخمسون دقيقة صباحاً".

الاستخدام الأساسي: humanize_times(text) — يبحث عن أي صيغة HH:MM داخل نص
(مع أو بدون كلمة "الساعة"/فترة صباحاً-مساءً حولها) ويستبدلها بالعبارة الكاملة.
"""
import re

# ---------- أسماء الساعات (١-١٢) — صيغة مؤنّثة تطابق "الساعة" ----------
_HOUR_WORDS = {
    1: 'الواحدة', 2: 'الثانية', 3: 'الثالثة', 4: 'الرابعة',
    5: 'الخامسة', 6: 'السادسة', 7: 'السابعة', 8: 'الثامنة',
    9: 'التاسعة', 10: 'العاشرة', 11: 'الحادية عشرة', 12: 'الثانية عشرة',
}

# ---------- دقائق ٣-٩ عند الإفراد: صيغة معكوسة (بلا تاء) + جمع "دقائق" ----------
# قاعدة العربية: العدد ٣-١٠ يعاكس تذكير/تأنيث المعدود؛ "دقيقة" مؤنثة
# لذلك تُستخدم الصيغة المذكّرة الظاهرية: ثلاث، أربع... (بلا تاء مربوطة)
_MIN_UNITS_PLURAL = {
    3: 'ثلاث', 4: 'أربع', 5: 'خمس', 6: 'ست', 7: 'سبع', 8: 'ثمان', 9: 'تسع',
}

# ---------- دقائق ١١-١٩: العدد المركّب "عشرة" يطابق تأنيث المعدود مباشرة ----------
_MIN_TEENS = {
    11: 'إحدى', 12: 'اثنتا', 13: 'ثلاث', 14: 'أربع', 15: 'خمس',
    16: 'ست', 17: 'سبع', 18: 'ثمان', 19: 'تسع',
}

# ---------- عقود الدقائق (١٠، ٢٠، ٣٠، ٤٠، ٥٠) ----------
_MIN_TENS = {10: 'عشر', 20: 'عشرون', 30: 'ثلاثون', 40: 'أربعون', 50: 'خمسون'}

# ---------- آحاد الدقائق عند التركيب مع عقد (٢١، ٣٢، ٥٣ ...) ----------
_MIN_COMPOUND_UNITS = {
    1: 'إحدى', 2: 'اثنتان', 3: 'ثلاث', 4: 'أربع', 5: 'خمس',
    6: 'ست', 7: 'سبع', 8: 'ثمان', 9: 'تسع',
}


def _minutes_to_words(m):
    """صياغة عدد الدقائق (١-٥٩) بعبارة عربية طبيعية (بدون كلمة الوصل 'و' البادئة)."""
    if m == 1:
        return 'دقيقة واحدة'
    if m == 2:
        return 'دقيقتين'
    if 3 <= m <= 9:
        return f'{_MIN_UNITS_PLURAL[m]} دقائق'
    if m == 10:
        return 'عشر دقائق'
    if 11 <= m <= 19:
        return f'{_MIN_TEENS[m]} عشرة دقيقة'
    if m % 10 == 0:
        return f'{_MIN_TENS[m]} دقيقة'
    tens, unit = (m // 10) * 10, m % 10
    return f'{_MIN_COMPOUND_UNITS[unit]} و{_MIN_TENS[tens]} دقيقة'


def time_to_arabic_phrase(hour, minute):
    """بناء عبارة عربية طبيعية كاملة لوقت (hour: 0-23, minute: 0-59).

    أمثلة:
        time_to_arabic_phrase(8, 53)  -> 'الساعة الثامنة وثلاث وخمسون دقيقة صباحاً'
        time_to_arabic_phrase(14, 0)  -> 'الساعة الثانية تماماً مساءً'
    """
    hour = int(hour) % 24
    minute = int(minute) % 60
    period = 'صباحاً' if hour < 12 else 'مساءً'
    hour12 = hour % 12 or 12

    phrase = f'الساعة {_HOUR_WORDS[hour12]}'
    if minute == 0:
        phrase += ' تماماً'
    else:
        phrase += f' و{_minutes_to_words(minute)}'
    return f'{phrase} {period}'


# نمط يلتقط وقتاً رقمياً HH:MM، مع "ابتلاع" أي كلمة "الساعة" قبله أو فترة
# (صباحاً/مساءً) بعده إن وُجدت مسبقاً في النص، بحيث يُستبدل الكل بالعبارة
# الموحّدة الكاملة بدل إضافتها فوق النص الأصلي (وإلا تتكرر الكلمة مرتين).
_TIME_RE = re.compile(
    r'(?:الساعة\s+)?'
    r'(?P<h>[01]?\d|2[0-3]):(?P<m>[0-5]\d)'
    r'(?:\s*(?:صباح(?:اً|ا)|مساء(?:اً|ً|ا)?))?'
)


def humanize_times(text):
    """استبدال كل وقت رقمي HH:MM داخل نص بصيغته العربية المنطوقة الطبيعية.

    آمنة للتطبيق أكثر من مرة على نفس النص (لا يبقى بعد أول تمرير أي نمط
    HH:MM لتطابقه دالة أخرى)، وتتجنب تكرار كلمة "الساعة" أو الفترة إن كانتا
    موجودتين أصلاً حول الرقم في النص المصدر.
    """
    if not text:
        return text

    def _repl(match):
        return time_to_arabic_phrase(int(match.group('h')), int(match.group('m')))

    return _TIME_RE.sub(_repl, text)
